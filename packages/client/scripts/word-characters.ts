/**
 * Generates `src/word-characters.ts`: the code points that are letters, marks, or
 * digits, as the running runtime's Unicode tables say, written down as ranges so the
 * Client never reads those tables itself. Run it with `bun run generate:word-characters`
 * from `packages/client` on a runtime of the Unicode version to pin, then format with
 * `bunx ultracite fix`.
 *
 * @packageDocumentation
 */

/** The highest code point. */
const lastCodePoint = 0x10_ff_ff;

const wordClass = /^[\p{L}\p{M}\p{N}]$/u;

/**
 * The Unicode version the running runtime's tables follow, such as `17.0`.
 * @returns The version, or `undefined` when the runtime does not say.
 */
export const runtimeUnicode = (): string | undefined => process.versions.unicode;

/**
 * Every code point that is a letter, a mark, or a digit, by the running runtime's tables,
 * as inclusive ranges, `[first, last, first, last, …]`, in order.
 * @returns The ranges.
 */
export const generateRanges = (): readonly number[] => {
  const ranges: number[] = [];
  let start: number | undefined;

  for (let code = 0; code <= lastCodePoint + 1; code += 1) {
    const inWord = code <= lastCodePoint && wordClass.test(String.fromCodePoint(code));

    if (inWord && start === undefined) {
      start = code;
    } else if (!inWord && start !== undefined) {
      ranges.push(start, code - 1);
      start = undefined;
    }
  }

  return ranges;
};

const hex = (code: number): string => `0x${code.toString(16)}`;

/**
 * The source of `src/word-characters.ts`.
 * @param version - The Unicode version the ranges follow.
 * @param ranges - The ranges.
 * @returns The module's text.
 */
const render = (version: string, ranges: readonly number[]): string =>
  `/**
 * The code points that are letters (L), marks (M), or digits (N) in Unicode ${version}, as
 * inclusive ranges, \`[first, last, first, last, …]\`, in order. Generated by
 * \`scripts/word-characters.ts\`: do not edit by hand. The Client reads these, never the
 * runtime's own Unicode tables, so the same Journal gives the same Highlights on every
 * runtime.
 *
 * @packageDocumentation
 */

/** The Unicode version these ranges follow. */
export const wordUnicode = "${version}";

/** Letters, marks, and digits, as inclusive ranges of code points. */
export const wordRanges: readonly number[] = [${ranges.map(hex).join(", ")}];
`;

if (import.meta.main) {
  const version = runtimeUnicode();

  if (version === undefined) {
    throw new Error("This runtime does not say which Unicode version its tables follow.");
  }

  await Bun.write(
    new URL("../src/word-characters.ts", import.meta.url),
    render(version, generateRanges())
  );
}
