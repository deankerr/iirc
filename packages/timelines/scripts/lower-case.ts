/**
 * Generates `src/lower-case.ts`: Unicode's simple lower-case mapping, one code point to
 * one, as the running runtime's tables say, written down as runs so a search never reads
 * those tables itself. Run it with `bun run generate:lower-case` from `packages/timelines`
 * on a runtime of the Unicode version to pin, then format with `bunx ultracite fix`.
 *
 * @packageDocumentation
 */

/** The highest code point. */
const lastCodePoint = 0x10_ff_ff;

/**
 * The simple mappings a runtime's `toLowerCase` does not give, because its full mapping
 * expands: U+0130 lower-cases to `i` and a combining dot in full, and to `i` alone simply,
 * as UnicodeData says. Any other that expands is a new one to read from UnicodeData.
 */
const expanding = new Map([[0x1_30, 0x69]]);

/**
 * The Unicode version the running runtime's tables follow, such as `17.0`.
 * @returns The version, or `undefined` when the runtime does not say.
 */
export const runtimeUnicode = (): string | undefined => process.versions.unicode;

/**
 * Each code point that lower-cases to another, by the running runtime's tables, as runs
 * `[first, last, step, delta, …]`: every `step`-th code point from `first` to `last`
 * lower-cases to itself plus `delta`.
 * @returns The runs, in order.
 */
export const generateRuns = (): readonly number[] => {
  const mappings: (readonly [number, number])[] = [];

  for (let code = 0; code <= lastCodePoint; code += 1) {
    if (code >= 0xd8_00 && code <= 0xdf_ff) {
      continue;
    }

    const lower = Array.from(
      String.fromCodePoint(code).toLowerCase().matchAll(/./gsu),
      ([each]) => each.codePointAt(0) ?? 0
    );

    const [only] = lower;

    if (lower.length === 1 && only !== undefined && only !== code) {
      mappings.push([code, only]);
    } else if (lower.length > 1) {
      const simple = expanding.get(code);

      if (simple === undefined) {
        throw new Error(`U+${code.toString(16)} expands, and has no simple mapping here`);
      }

      mappings.push([code, simple]);
    }
  }

  const runs: number[] = [];

  for (const [code, lower] of mappings) {
    const delta = lower - code;
    const { length } = runs;
    const last = runs[length - 3];
    const step = runs[length - 2];

    if (
      length > 0 &&
      runs[length - 1] === delta &&
      last !== undefined &&
      ((step === 0 && (code - last === 1 || code - last === 2)) || code - last === step)
    ) {
      runs[length - 3] = code;
      runs[length - 2] = code - last;
    } else {
      runs.push(code, code, 0, delta);
    }
  }

  // A run of one has no step; give it 1, so every step is positive.
  return runs.map((each, index) => (index % 4 === 2 && each === 0 ? 1 : each));
};

const hex = (code: number): string => `0x${code.toString(16)}`;

/**
 * The source of `src/lower-case.ts`.
 * @param version - The Unicode version the runs follow.
 * @param runs - The runs.
 * @returns The module's text.
 */
const render = (version: string, runs: readonly number[]): string =>
  `/**
 * Unicode ${version}'s simple lower-case mapping, one code point to one, as runs
 * \`[first, last, step, delta, …]\`: every \`step\`-th code point from \`first\` to \`last\`
 * lower-cases to itself plus \`delta\`. Generated by \`scripts/lower-case.ts\`: do not edit
 * by hand. A search folds text by these, never the runtime's own Unicode tables, so every
 * store and every runtime finds the same Messages.
 *
 * @packageDocumentation
 */

/** The Unicode version these runs follow. */
export const lowerCaseUnicode = "${version}";

/** The simple lower-case mapping, as runs. */
export const lowerCaseRuns: readonly number[] = [${runs.map((each, index) => (index % 4 === 3 ? String(each) : hex(each))).join(", ")}];
`;

if (import.meta.main) {
  const version = runtimeUnicode();

  if (version === undefined) {
    throw new Error("This runtime does not say which Unicode version its tables follow.");
  }

  await Bun.write(
    new URL("../src/lower-case.ts", import.meta.url),
    render(version, generateRuns())
  );
}
