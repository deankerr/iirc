/**
 * Generates `src/decompositions.ts`: each code point's canonical decomposition, followed
 * down to its end, with the marks of the Combining Diacritical Marks block (U+0300 to
 * U+036F) dropped, as the running runtime's tables say, written down so a search never
 * reads those tables itself. Run it with `bun run generate:decompositions` from
 * `packages/timelines` on a runtime of the Unicode version to pin, then format with
 * `bunx ultracite fix`.
 *
 * @packageDocumentation
 */

import { runtimeUnicode } from "./lower-case.ts";

/** The highest code point. */
const lastCodePoint = 0x10_ff_ff;

/**
 * Whether a code point is a mark a search drops: one of the Combining Diacritical Marks.
 * @param code - A code point.
 * @returns Whether it is dropped.
 */
const isDroppedMark = (code: number): boolean => code >= 0x3_00 && code <= 0x3_6f;

/**
 * Whether a code point is a Hangul syllable, which Unicode decomposes by arithmetic and
 * not by UnicodeData's table, and which a search keeps whole.
 * @param code - A code point.
 * @returns Whether it is one.
 */
const isHangulSyllable = (code: number): boolean => code >= 0xac_00 && code <= 0xd7_a3;

/**
 * What a code point decomposes to, by the running runtime's canonical decomposition, its
 * dropped marks taken out.
 * @param code - A code point.
 * @returns The code points it decomposes to, which may be none.
 */
export const runtimeBaseOf = (code: number): readonly number[] => {
  const whole = String.fromCodePoint(code);
  const decomposed = isHangulSyllable(code) ? whole : whole.normalize("NFD");

  return Array.from(decomposed.matchAll(/./gsu), ([each]) => each.codePointAt(0) ?? 0).filter(
    (each) => !isDroppedMark(each)
  );
};

/**
 * Each code point a search takes to something else, as `[code, count, …base]`: the code
 * point, how many code points follow, and those code points.
 * @returns The entries, in order.
 */
const generateEntries = (): readonly number[] => {
  const entries: number[] = [];

  for (let code = 0; code <= lastCodePoint; code += 1) {
    if (code >= 0xd8_00 && code <= 0xdf_ff) {
      continue;
    }

    const whole = String.fromCodePoint(code);

    // A search lower-cases a letter before it decomposes it, so one that lower-cases to
    // another is never looked up here.
    if (whole.toLowerCase() !== whole) {
      continue;
    }

    const base = runtimeBaseOf(code);

    if (base.length !== 1 || base[0] !== code) {
      const lowered = String.fromCodePoint(...base);

      // So a lower-case letter's base must need no lower-casing of its own.
      if (lowered.toLowerCase() !== lowered) {
        throw new Error(`U+${code.toString(16)} decomposes to an upper-case letter`);
      }

      entries.push(code, base.length, ...base);
    }
  }

  return entries;
};

const hex = (code: number): string => `0x${code.toString(16)}`;

/**
 * The source of `src/decompositions.ts`.
 * @param version - The Unicode version the entries follow.
 * @param entries - The entries.
 * @returns The module's text.
 */
const render = (version: string, entries: readonly number[]): string =>
  `/**
 * Unicode ${version}'s canonical decompositions, followed down to their end, with the marks
 * of the Combining Diacritical Marks block (U+0300 to U+036F) dropped, as entries
 * \`[code, count, …base]\`: the code point, how many code points it becomes, and those. A
 * code point not listed stays as it is, as a Hangul syllable does, and one that
 * lower-cases to another is not listed, as a search lower-cases it first. Generated by
 * \`scripts/decompositions.ts\`: do not edit by hand. A search folds text by these, never
 * the runtime's own Unicode tables, so every store and every runtime finds the same
 * Messages.
 *
 * @packageDocumentation
 */

/** The Unicode version these entries follow. */
export const decompositionUnicode = "${version}";

/** Each code point's base, as entries. */
export const decompositionEntries: readonly number[] = [${entries.map(hex).join(", ")}];
`;

if (import.meta.main) {
  const version = runtimeUnicode();

  if (version === undefined) {
    throw new Error("This runtime does not say which Unicode version its tables follow.");
  }

  await Bun.write(
    new URL("../src/decompositions.ts", import.meta.url),
    render(version, generateEntries())
  );
}
